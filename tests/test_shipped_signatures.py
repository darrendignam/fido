"""Guards on the signature files that ship with FIDO.

formats-v*.xml is a build product generated by fido-prepare and committed to
the repository, so a generator bug reaches users even once the generator is
fixed. These tests check the artefact itself.
"""

import glob
import os
import re

import pytest
from defusedxml.ElementTree import parse as safe_parse

from fido import CONFIG_DIR


def shipped_signature_files():
    return sorted(glob.glob(os.path.join(CONFIG_DIR, "formats-v*.xml")))


def patterns_in(path):
    for fmt in safe_parse(path).getroot().iter("format"):
        puid = fmt.findtext("puid")
        for pattern in fmt.iter("pattern"):
            yield puid, pattern.findtext("position"), pattern.findtext("regex") or ""


@pytest.mark.parametrize("path", shipped_signature_files())
def test_every_shipped_pattern_compiles(path):
    """Five patterns once shipped with min > max, so those formats never matched."""
    broken = []
    for puid, position, regex in patterns_in(path):
        try:
            re.compile(regex)
        except re.error as err:
            broken.append("{} {}: {} ({})".format(puid, position, err, regex[:60]))

    assert not broken, "uncompilable patterns in {}:\n{}".format(os.path.basename(path), "\n".join(broken))


@pytest.mark.parametrize("path", shipped_signature_files())
def test_no_shipped_pattern_uses_a_zero_width_negation(path):
    """PRONOM [!XX] must consume a byte, otherwise every later offset shifts."""
    offenders = [
        "{} {}".format(puid, position)
        for puid, position, regex in patterns_in(path)
        if "(?!" in regex and "(?:(?!" not in regex
    ]

    assert not offenders, "zero-width negations in {}: {}".format(os.path.basename(path), offenders)


@pytest.mark.parametrize("path", shipped_signature_files())
def test_no_shipped_pattern_makes_a_wildcard_optional(path):
    """PRONOM ?? is exactly one byte, so ".?" would also match its absence."""
    offenders = [
        "{} {}".format(puid, position) for puid, position, regex in patterns_in(path) if ".?" in regex
    ]

    assert not offenders, "optional wildcards in {}: {}".format(os.path.basename(path), offenders)


@pytest.mark.parametrize("path", shipped_signature_files())
def test_shipped_signature_file_is_not_empty(path):
    """An HTML error page installed over the signatures parses but holds no formats."""
    formats = list(safe_parse(path).getroot().iter("format"))

    assert len(formats) > 2000, "{} holds only {} formats".format(os.path.basename(path), len(formats))
